import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {parseVisualJson} from '../apps/web/src/lib/visual-json.ts';
import {validCompleteDraft} from '../apps/web/src/lib/visual-studio-profile.ts';
import {parseCompositionResult} from '../apps/web/src/lib/eye-composition-result.ts';
import {parseCatalogSnapshot} from '../apps/web/src/lib/catalog-snapshot.ts';
import {parseVisualStatus} from '../apps/web/src/lib/visual-status-report.ts';
const root=process.argv[2];
if(!root)throw Error('Explicit fixture directory required');
const load=(name,budget=128*1024)=>parseVisualJson(readFileSync(join(root,name+'.json'),'utf8'),budget);
const a=load('profile-a'),b=load('profile-b');
assert.ok(validCompleteDraft(a)&&validCompleteDraft(b));
assert.equal(a.robot_id,'fixture-one');assert.equal(b.robot_id,'fixture-two');
assert.ok(a.zones.every(z=>z.adapter_id===null));assert.ok(b.zones.every(z=>z.capabilities.includes('eye_expression')));
assert.ok(!b.zones.some(z=>z.capabilities.includes('solid')));
const composition=load('composition'),blank=load('blank');
assert.equal(parseCompositionResult(composition,'fixture-one').functional_scene,'speaking');
assert.equal(parseCompositionResult(blank,'fixture-one').blank_pixels_intent,true);
assert.throws(()=>parseCompositionResult(composition,'fixture-two'));
assert.throws(()=>parseCompositionResult({...composition,hardware_commands_sent:true},'fixture-one'));
assert.throws(()=>parseCompositionResult({...composition,eye_frame_plan:{...composition.eye_frame_plan,robot_identity_claim:'fake'}},'fixture-one'));
assert.throws(()=>parseCompositionResult({...composition,eye_frame_plan:{...composition.eye_frame_plan,eye_frames:{...composition.eye_frame_plan.eye_frames,left:{...composition.eye_frame_plan.eye_frames.left,applied:true}}}},'fixture-one'));
const director=load('director',2*1024*1024);
assert.ok(director.length>1);
for(const frame of director)parseCompositionResult(frame,'fixture-one');
const rawCatalog=load('catalog',2*1024*1024);
const catalog=parseCatalogSnapshot(rawCatalog,'fixture-one');
assert.equal(catalog.expressions[0].latest_revision,3);
assert.equal(catalog.expressions[0].revisions[2].action,'rollback');
assert.throws(()=>parseCatalogSnapshot(rawCatalog,'fixture-two'));
assert.throws(()=>parseCatalogSnapshot({...rawCatalog,hardware_execution_authorized:true},'fixture-one'));
const status=load('status');
const d=parseVisualStatus(status);
assert.equal(d.freshness,'unknown');assert.equal(d.physicalOutputObserved,false);
assert.equal(d.desired,'speaking');assert.equal(d.applied,'idle');
assert.throws(()=>parseVisualStatus({...status,robot_binding_verified:true}));
assert.throws(()=>parseVisualStatus({...status,physical_output_observed:true}));
assert.throws(()=>parseCompositionResult(status,'fixture-one'));
assert.throws(()=>parseVisualStatus(composition));
console.log(JSON.stringify({profiles:2,composer:2,directorFrames:director.length,catalogRevisions:3,unboundStatusReports:status.reports.length,physicalAuthority:false}));
